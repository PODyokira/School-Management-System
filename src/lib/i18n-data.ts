export const dicts = { en, fr };
export type Dict = typeof en;

export function getLangFromCookie(cookieHeader?: string | null): Lang {
  if (!cookieHeader) return "en";
  const m = cookieHeader.match(/(?:^|;\s*)lang=(en|fr)/);
  return (m?.[1] as Lang) || "en";
}

export function getDict(lang: Lang): Dict { return dicts[lang] || dicts.en; }

export function tr(t: Dict, text: string, map?: Record<string,string>): string {
  if (!text) return text;
  return (map && map[text]) || (t.domain.classes[text]) || (t.domain.subjects[text]) || (t.domain.assessments[text]) || (t.domain.academicYears[text]) || (t.statuses as any)[text] || (t.relationships as any)[text] || text;
}

export function fmt(template: string, vars: Record<string,string|number>) {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}
